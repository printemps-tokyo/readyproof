//! `--fix`: write starter files for what is missing.
//!
//! Planning is pure (a snapshot in, files to create out); `main.rs` writes
//! them. The fixer only ever creates files that do not exist. Each template
//! leaves the decisions to the maintainer: where a file would make a promise
//! (a contact address, a response time, supported versions), it holds a
//! marked placeholder instead, and the checks keep reporting it until the
//! placeholder is replaced. It never writes a LICENSE: choosing one is not a
//! default anyone else should make.

use crate::checks::disclosure::SECURITY_CANDIDATES;
use crate::checks::docs::{COC_CANDIDATES, CONTRIBUTING_CANDIDATES, LICENSE_CANDIDATES};
use crate::checks::supply::UPDATE_CONFIGS;
use crate::snapshot::RepoSnapshot;

/// One file to create.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewFile {
    pub path: &'static str,
    pub contents: String,
    /// The check this answers.
    pub check: &'static str,
}

/// Something the fixer will not do, with the reason.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Skipped {
    pub check: &'static str,
    pub reason: &'static str,
}

/// The plan: files to create and things left to the maintainer.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct FixPlan {
    pub create: Vec<NewFile>,
    pub skipped: Vec<Skipped>,
}

const SECURITY_MD: &str = "\
# Security policy

## Reporting a vulnerability

Please do not report security problems in public issues.

<!-- readyproof: replace the address below with a monitored one, or turn on
     GitHub's reporting feature under Settings -> Code security and link to
     its page here. readyproof warns while the address is a placeholder. -->
Send vulnerability reports privately to security@example.com.

<!-- readyproof: add one sentence giving a first-response time you can
     actually meet, as a number of days. -->

## Supported versions

<!-- readyproof: say which versions receive security fixes. \"Only the latest
     release\" is a complete answer. -->
";

const CONTRIBUTING_MD: &str = "\
# Contributing

Thank you for your interest in contributing.

## Building and testing

<!-- readyproof: list the commands that build the project and run its tests. -->

## Proposing a change

1. Open an issue first for anything larger than a small fix.
2. Fork the repository and create a branch.
3. Make sure the tests pass, then open a pull request describing the change.

## Reporting a security problem

See SECURITY.md. Please do not open a public issue for a vulnerability.
";

const CODE_OF_CONDUCT_MD: &str = "\
# Code of conduct

This project adopts the Contributor Covenant, version 2.1:
https://www.contributor-covenant.org/version/2/1/code_of_conduct/

<!-- readyproof: name who receives reports and how to reach them, for example
     a monitored address. -->
Report unacceptable behavior to the maintainers.
";

/// Dependabot ecosystems for root-level manifests, from GitHub's Dependabot
/// options reference (package-ecosystem values, read 2026-11-12).
const ECOSYSTEMS: &[(&[&str], &str)] = &[
    (&["Cargo.toml"], "cargo"),
    (&["package.json"], "npm"),
    (&["go.mod"], "gomod"),
    (
        &["pyproject.toml", "requirements.txt", "Pipfile", "setup.py"],
        "pip",
    ),
    (&["Gemfile"], "bundler"),
    (&["composer.json"], "composer"),
    (&["Dockerfile"], "docker"),
];

fn dependabot_yml(ecosystems: &[&str]) -> String {
    let mut out = String::from(
        "# Generated by readyproof --fix. Adjust the schedule and add directories\n\
         # for packages that are not at the repository root.\n\
         version: 2\n\
         updates:\n",
    );
    for eco in ecosystems {
        out.push_str(&format!(
            "  - package-ecosystem: \"{eco}\"\n    directory: \"/\"\n    schedule:\n      interval: \"weekly\"\n"
        ));
    }
    out
}

/// Plan the files to create for `snap`.
pub fn plan(snap: &RepoSnapshot) -> FixPlan {
    let mut plan = FixPlan::default();
    if snap.find_first(SECURITY_CANDIDATES).is_none() {
        plan.create.push(NewFile {
            path: "SECURITY.md",
            contents: SECURITY_MD.to_string(),
            check: "disclosure-policy",
        });
    }
    if snap.find_first(CONTRIBUTING_CANDIDATES).is_none() {
        plan.create.push(NewFile {
            path: "CONTRIBUTING.md",
            contents: CONTRIBUTING_MD.to_string(),
            check: "doc-contributing",
        });
    }
    if snap.find_first(COC_CANDIDATES).is_none() {
        plan.create.push(NewFile {
            path: "CODE_OF_CONDUCT.md",
            contents: CODE_OF_CONDUCT_MD.to_string(),
            check: "doc-code-of-conduct",
        });
    }
    if snap.find_first(UPDATE_CONFIGS).is_none() {
        let mut ecosystems: Vec<&str> = ECOSYSTEMS
            .iter()
            .filter(|(files, _)| snap.find_first(files).is_some())
            .map(|(_, eco)| *eco)
            .collect();
        if snap.paths_under(".github/workflows/").next().is_some() {
            ecosystems.push("github-actions");
        }
        if ecosystems.is_empty() {
            plan.skipped.push(Skipped {
                check: "supply-updates",
                reason: "no root-level manifest or workflow for Dependabot to watch",
            });
        } else {
            plan.create.push(NewFile {
                path: ".github/dependabot.yml",
                contents: dependabot_yml(&ecosystems),
                check: "supply-updates",
            });
        }
    }
    if snap.find_first(LICENSE_CANDIDATES).is_none() {
        plan.skipped.push(Skipped {
            check: "license-present",
            reason: "choosing a license is the maintainer's decision; add LICENSE yourself",
        });
    }
    plan
}

#[cfg(test)]
mod tests {
    use super::*;

    fn snap(files: &[&str]) -> RepoSnapshot {
        RepoSnapshot::from_entries("x", files.iter().map(|f| (*f, None::<&str>)))
    }

    #[test]
    fn a_bare_repository_gets_every_template_but_a_license() {
        let plan = plan(&snap(&[
            "Cargo.toml",
            ".github/workflows/ci.yml",
            "src/main.rs",
        ]));
        let paths: Vec<&str> = plan.create.iter().map(|f| f.path).collect();
        assert_eq!(
            paths,
            vec![
                "SECURITY.md",
                "CONTRIBUTING.md",
                "CODE_OF_CONDUCT.md",
                ".github/dependabot.yml"
            ]
        );
        let dependabot = &plan.create[3].contents;
        assert!(dependabot.contains("package-ecosystem: \"cargo\""));
        assert!(dependabot.contains("package-ecosystem: \"github-actions\""));
        assert!(!dependabot.contains("\"npm\""));
        assert_eq!(plan.skipped.len(), 1);
        assert_eq!(plan.skipped[0].check, "license-present");
    }

    #[test]
    fn existing_files_are_never_planned() {
        let plan = plan(&snap(&[
            ".github/SECURITY.md",
            "docs/CONTRIBUTING.md",
            "CODE_OF_CONDUCT.md",
            "renovate.json",
            "LICENSE",
        ]));
        assert_eq!(plan, FixPlan::default());
    }

    #[test]
    fn no_manifest_means_no_dependabot_file() {
        let plan = plan(&snap(&["README.md", "LICENSE"]));
        assert!(plan
            .create
            .iter()
            .all(|f| f.path != ".github/dependabot.yml"));
        assert!(plan.skipped.iter().any(|s| s.check == "supply-updates"));
    }

    #[test]
    fn the_security_template_keeps_its_promises_open() {
        // The placeholder address is flagged as a placeholder, and no
        // response time is stated on the maintainer's behalf.
        let text = SECURITY_MD;
        let email = crate::text::find_email(text).unwrap();
        assert!(email.placeholder);
        assert!(crate::text::find_private_channel(&text.to_ascii_lowercase()).is_none());
        assert!(crate::text::find_response_time(text).is_none());
    }
}
