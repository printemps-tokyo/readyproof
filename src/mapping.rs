//! How readyproof's checks line up with OpenSSF Scorecard and SLSA.
//!
//! The mapping says what each readyproof check has in common with a
//! Scorecard check or a SLSA level, and where they differ. It never claims
//! that passing readyproof means passing Scorecard: Scorecard reads the
//! hosting platform's API and history, readyproof reads the files of a local
//! checkout, so the same practice is often observed in different ways.

/// How closely a readyproof check corresponds to a Scorecard check.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Relation {
    /// Both look for the same thing in essentially the same place.
    Same,
    /// The same practice, observed differently or only in part.
    Partial,
}

impl Relation {
    pub fn as_str(self) -> &'static str {
        match self {
            Relation::Same => "same",
            Relation::Partial => "partial",
        }
    }
}

/// One readyproof check's correspondences.
#[derive(Debug, Clone, Copy)]
pub struct Mapping {
    pub check: &'static str,
    /// Scorecard checks, with how closely each corresponds.
    pub scorecard: &'static [(&'static str, Relation)],
    /// The SLSA level the evidence bears on, if any.
    pub slsa: Option<&'static str>,
    /// What differs, in one sentence.
    pub note: &'static str,
}

