/// The mapping for one check id.
pub fn mapping(check: &str) -> Option<&'static Mapping> {
    MAPPINGS.iter().find(|m| m.check == check)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_check_is_mapped_once() {
        let ids = crate::checks::check_ids();
        assert_eq!(ids.len(), MAPPINGS.len());
        for id in ids {
            assert!(mapping(id).is_some(), "{id} has no mapping");
        }
    }

    #[test]
    fn scorecard_names_are_real_and_not_double_listed() {
        // The 20 checks in Scorecard's docs/checks.md at the cited commit.
        const SCORECARD: [&str; 20] = [
            "Binary-Artifacts",
            "Branch-Protection",
            "CI-Tests",
            "CII-Best-Practices",
            "Code-Review",
            "Contributors",
            "Dangerous-Workflow",
            "Dependency-Update-Tool",
            "Fuzzing",
            "License",
            "Maintained",
            "Packaging",
            "Pinned-Dependencies",
            "SAST",
            "SBOM",
            "Security-Policy",
            "Signed-Releases",
            "Token-Permissions",
            "Vulnerabilities",
            "Webhooks",
        ];
        let covered: Vec<&str> = MAPPINGS
            .iter()
            .flat_map(|m| m.scorecard.iter().map(|(s, _)| *s))
            .collect();
        for name in covered.iter().chain(NOT_COVERED.iter().map(|(s, _)| s)) {
            assert!(SCORECARD.contains(name), "{name}");
        }
        for name in SCORECARD {
            let mapped = covered.contains(&name);
            let listed = NOT_COVERED.iter().any(|(s, _)| *s == name);
            assert!(
                mapped != listed,
                "{name} must be either mapped or listed as not covered"
            );
        }
    }
}
